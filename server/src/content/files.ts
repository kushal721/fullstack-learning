// Text may use `backticks` for inline code.

type FileInput = Omit<ProjectFile, "id" | "path" | "layer">;

/** The id is the path; the layer is its first folder. */
function file(path: string, input: FileInput): ProjectFile {
  const top = path.split("/")[0];
  const layer =
    top === "frontend" || top === "backend" || top === "database"
      ? top
      : "root";
  return { id: path, path, layer, ...input };
}

